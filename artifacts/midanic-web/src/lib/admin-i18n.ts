export function useAdminText() {
  const { i18n } = useTranslation();
  const language = (i18n.language.startsWith('ar')
    ? 'ar'
    : i18n.language.startsWith('fr')
      ? 'fr'
      : 'en') as SupportedLanguage;

  return {
    tAdmin: (text: string) => translations[language][text] ?? text,
  };
}